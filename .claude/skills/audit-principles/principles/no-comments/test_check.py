#!/usr/bin/env python3
"""Tests for check.py and audit.py propose. Never installed into a repo.

  python3 -I -m unittest discover -s <this folder> -p 'test_*.py'
"""
import argparse
import contextlib
import io
import os
import subprocess
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import audit
import check

CFG = {"roots": ["src", "App", "tests", "AppTests"], "exclude": ["src/gen/*"], "tests": ["tests/*", "AppTests/*"],
       "allow": [], "ticket_keys": ["ABC"], "rules": {"comment": "baseline", "history-id": "baseline"}}


def write_repo(files):
    root = tempfile.mkdtemp()
    for rel, text in files.items():
        os.makedirs(os.path.join(root, os.path.dirname(rel)), exist_ok=True)
        with open(os.path.join(root, rel), "w", encoding="utf-8") as fh:
            fh.write(text)
    return root


def found(files, cfg=CFG):
    report = check.measure(write_repo(files), check.Config(cfg))
    return {r: [(v["file"], v["line"], v["kind"]) for v in report["violations"][r]] for r in check.RULES}


class TypeScriptComments(unittest.TestCase):
    def test_line_block_and_doc_comments_count(self):
        out = found({"src/a.ts": "// one\nconst a = 1; /* two */\n/** three */\nexport {};\n",
                     "src/gen/b.ts": "// generated elsewhere\n"})
        self.assertEqual(out["comment"], [("src/a.ts", 1, "line"), ("src/a.ts", 2, "block"), ("src/a.ts", 3, "doc")])

    def test_strings_templates_and_regex_literals_are_not_comments(self):
        out = found({"src/a.ts": '#!/usr/bin/env node\nconst u = "http://x";\nconst t = `a ${"//"} b // c`;\n'
                                 "const r = /\\/\\/[^/]*/g;\nconst s = '/* no */';\nconst d = a / b / c;\n"})
        self.assertEqual(out["comment"], [])

    def test_a_comment_inside_template_interpolation_counts(self):
        out = found({"src/a.ts": "const t = `x ${y /* why */} z`;\n"})
        self.assertEqual(out["comment"], [("src/a.ts", 1, "block")])

    def test_the_two_exceptions_pass(self):
        out = found({"src/a.ts": "// @generated by tool\n// eslint-disable-next-line no-new -- side effect only\nnew X();\n"
                                 "// eslint-disable-next-line no-new\n// eslint-disable-next-line a, b -- two rules\n"})
        self.assertEqual(out["comment"], [("src/a.ts", 4, "line"), ("src/a.ts", 5, "line")])

    def test_an_allow_pattern_passes_its_comments(self):
        cfg = dict(CFG, allow=[r"^@ts-expect-error\b"])
        out = found({"src/a.ts": "// @ts-expect-error — wrong on purpose\nf(1);\n// @ts-ignore\n"}, cfg)
        self.assertEqual(out["comment"], [("src/a.ts", 3, "line")])


class SwiftComments(unittest.TestCase):
    def test_comment_kinds_and_nested_blocks(self):
        out = found({"App/A.swift": "/// doc\n// MARK: - Section\n/* outer /* inner */ still */\nlet a = 1 // why\n"})
        self.assertEqual(out["comment"], [("App/A.swift", 1, "doc"), ("App/A.swift", 2, "mark"),
                                          ("App/A.swift", 3, "block"), ("App/A.swift", 4, "line")])

    def test_strings_raw_strings_and_interpolation_are_not_comments(self):
        out = found({"App/A.swift": 'let a = "http://x"\nlet b = #"a "// b" c"#\nlet c = """\n// not\n"""\n'
                                    'let d = "\\(f("//")) /* no */"\n'})
        self.assertEqual(out["comment"], [])


class CssComments(unittest.TestCase):
    def test_block_comments_count_outside_strings(self):
        out = found({"src/a.css": '.a { content: "/* no */"; }\n/* ABC-12: why */\n.b {}\n'})
        self.assertEqual(out["comment"], [("src/a.css", 2, "block")])


class HistoryIds(unittest.TestCase):
    def test_ids_in_ts_titles_and_file_names(self):
        out = found({
            "tests/abc-108-proof.test.ts": 'describe("ABC-108 proof", () => {\n  it.skip("covers behavior 4", () => {});\n'
                                           '  it("renders the list", () => {});\n});\n',
            "src/abc-9.ts": 'it("ABC-9", () => {});\n',
        })
        self.assertEqual(out["history-id"], [("tests/abc-108-proof.test.ts", 0, "file-name"),
                                             ("tests/abc-108-proof.test.ts", 1, "title"),
                                             ("tests/abc-108-proof.test.ts", 2, "title")])

    def test_ids_in_swift_titles_reasons_and_names(self):
        out = found({"AppTests/ParserTests.swift":
                     '@Suite("Parser")\nstruct ParserTests {\n  @Test("AMB-1 parses", .disabled("AMB-3: unclear"))\n'
                     '  func parses() {}\n  func testAbc12Regression() {}\n  func skips() throws { throw XCTSkip("QA-B3 flaky") }\n}\n'})
        self.assertEqual(out["history-id"], [("AppTests/ParserTests.swift", 3, "title"),
                                             ("AppTests/ParserTests.swift", 3, "reason"),
                                             ("AppTests/ParserTests.swift", 5, "name"),
                                             ("AppTests/ParserTests.swift", 6, "reason")])

    def test_a_title_inside_a_comment_is_only_a_comment(self):
        out = found({"tests/a.test.ts": '// it("ABC-1 old", () => {})\n'})
        self.assertEqual(out["history-id"], [])
        self.assertEqual(out["comment"], [("tests/a.test.ts", 1, "line")])

    def test_ticket_keys_come_from_config(self):
        out = found({"tests/a.test.ts": 'it("ENG-4 and UTF-8", () => {});\n'}, dict(CFG, ticket_keys=["ENG"]))
        self.assertEqual(out["history-id"], [("tests/a.test.ts", 1, "title")])
        out = found({"tests/a.test.ts": 'it("ENG-4 and UTF-8", () => {});\n'})
        self.assertEqual(out["history-id"], [])


class Baseline(unittest.TestCase):
    def setUp(self):
        self.files = {"src/a.ts": "// first\nf();\n// second\n"}
        self.cfg = check.Config(CFG)

    def run_check(self, files, known, base=None):
        report = check.measure(write_repo(files), self.cfg)
        return check.check(report, self.cfg, {"known": known}, base, None)[0]

    def known(self):
        return [v["key"] for v in check.measure(write_repo(self.files), self.cfg)["violations"]["comment"]]

    def test_known_comments_pass_after_other_code_moves(self):
        self.assertEqual(self.run_check({"src/a.ts": "g();\n// second\nf();\n// first\n"}, self.known()), [])

    def test_a_new_comment_fails_at_its_line(self):
        problems = self.run_check({"src/a.ts": "// new\n// first\nf();\n// second\n"}, self.known())
        self.assertEqual(len(problems), 1)
        self.assertIn("src/a.ts:1: [comment]", problems[0])

    def test_editing_a_known_comment_fails_and_leaves_a_stale_entry(self):
        problems = self.run_check({"src/a.ts": "// first, reworded\nf();\n// second\n"}, self.known())
        self.assertEqual(len(problems), 2)
        self.assertIn("[stale]", problems[1])

    def test_a_fixed_violation_must_leave_the_baseline(self):
        problems = self.run_check({"src/a.ts": "// first\nf();\n"}, self.known())
        self.assertEqual(len(problems), 1)
        self.assertIn("[stale]", problems[0])

    def test_a_baseline_that_grew_against_the_base_fails(self):
        problems = self.run_check(self.files, self.known(), base={"known": self.known()[:1]})
        self.assertEqual(len(problems), 1)
        self.assertIn("[grew]", problems[0])

    def test_strict_fails_every_violation(self):
        self.cfg = check.Config(dict(CFG, rules={"comment": "strict"}))
        self.assertEqual(len(self.run_check(self.files, [])), 2)


class Propose(unittest.TestCase):
    def test_drafts_roots_tests_excludes_keys_and_rule_modes(self):
        root = write_repo({
            "src/a.ts": "// why\nexport {};\n",
            "src/tokens.generated.ts": "export {};\n",
            "src/b.ts": "// @generated by tokens\nexport {};\n",
            "App/Generated/Protocol.swift": "// Code generated, DO NOT EDIT.\n",
            "App/View.swift": "let a = 1\n",
            "AppTests/ViewTests.swift": "func testView() {}\n",
            "tests/a.test.ts": 'it("renders", () => {});\n',
            "node_modules/x/index.js": "// vendored\n",
        })
        subprocess.run(["git", "init", "-q", root], check=True)
        subprocess.run(["git", "-C", root, "add", "."], check=True)
        for msg in ("ABC-1 one", "ABC-2 two", "ABC-3 three", "UTF-8 fix"):
            subprocess.run(["git", "-C", root, "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q",
                            "--allow-empty", "-m", msg], check=True)
        out = os.path.join(root, "config.json")
        with contextlib.redirect_stdout(io.StringIO()):
            audit.propose(argparse.Namespace(root=root, out=out))
        cfg = check.load_json(out)
        self.assertEqual(cfg["roots"], ["App", "AppTests", "src", "tests"])
        self.assertEqual(cfg["exclude"], ["App/Generated/*", "src/b.ts", "src/tokens.generated.ts"])
        self.assertEqual(cfg["tests"], ["*.spec.*", "*.test.*", "AppTests/*", "tests/*"])
        self.assertEqual(cfg["ticket_keys"], ["ABC"])
        self.assertEqual(cfg["rules"], {"comment": "baseline", "history-id": "strict"})


if __name__ == "__main__":
    unittest.main()
